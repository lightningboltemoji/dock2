import Foundation

/// What a copy was, by the first of these its types include ([clipboard](product/clipboard.md#what-is-kept)).
public enum ClipKind: String, Codable, Sendable, CaseIterable {
    case files, image, color, link, richText, text
}

/// What to do with a copy: keep it as a kind, or not, and why not.
public enum ClipDecision: Equatable, Sendable {
    case keep(ClipKind)
    case skip(Skip)

    public enum Skip: Equatable, Sendable {
        /// Marked by the app that copied it: a password, a transient value, something generated.
        case marked
        case ignoredApp
        case tooLarge
        /// Nothing dock2 keeps: a type of the copying app's own.
        case nothingKept
    }
}

/// Decides from what a copy says about itself, never its contents.
public enum ClipboardPolicy {
    /// The nspasteboard.org conventions password managers and others follow.
    public static let markers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    /// Password managers, out of the box.
    public static let ignoredByDefault: [String] = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.apple.Passwords",
        "com.apple.keychainaccess",
    ]

    /// The largest copy kept, in bytes: an image beyond it is let go.
    public static let sizeCap = 10 * 1024 * 1024

    static let typesByKind: [(ClipKind, Set<String>)] = [
        (.files, ["public.file-url", "NSFilenamesPboardType"]),
        (.image, ["public.png", "public.tiff", "public.jpeg", "public.heic"]),
        (.color, ["com.apple.cocoa.pasteboard.color"]),
        (.link, ["public.url"]),
        (.richText, ["public.rtf", "public.html", "com.apple.flat-rtfd"]),
        (.text, ["public.utf8-plain-text", "public.plain-text", "NSStringPboardType"]),
    ]

    /// The types a kind keeps: everything of its family, so rich text pastes back as rich text.
    public static func types(for kind: ClipKind, among types: [String]) -> [String] {
        let family: Set<String> = switch kind {
        case .richText: typesByKind.first { $0.0 == .richText }!.1.union(typesByKind.first { $0.0 == .text }!.1)
        case .link: typesByKind.first { $0.0 == .link }!.1.union(typesByKind.first { $0.0 == .text }!.1)
        default: typesByKind.first { $0.0 == kind }!.1
        }
        return types.filter(family.contains)
    }

    public static func decide(types: [String], frontApp: String?, ignored: Set<String>, size: Int) -> ClipDecision {
        if types.contains(where: markers.contains) { return .skip(.marked) }
        if let frontApp, ignored.contains(frontApp) { return .skip(.ignoredApp) }
        if size > sizeCap { return .skip(.tooLarge) }
        let present = Set(types)
        guard let kind = typesByKind.first(where: { !$0.1.isDisjoint(with: present) })?.0 else { return .skip(.nothingKept) }
        return .keep(kind)
    }
}

/// One copy, as the history keeps it; its data lives apart, loaded when needed.
public struct ClipEntry: Codable, Equatable, Sendable, Identifiable {
    public let id: String
    public var kind: ClipKind
    /// The text's first line, a file's name, the link.
    public var title: String
    /// Files' paths, for a copy of files: what search matches besides the title.
    public var files: [String]
    /// The bytes' digest, which makes a copy of the same thing the same entry.
    public var digest: String
    public var date: Date
    public var sourceApp: String?
    public var sourceName: String?
    public var pinned: Bool
    /// What the data holds, by type: kept to put every one back.
    public var types: [String]
    public var size: Int
    /// A copied image, small, as a PNG: its row's icon, made once when it was copied.
    public var thumbnail: Data?
    /// The copy's text as it is matched (`searchText(from:)`): what an entry is found by besides its title
    /// and its files' names, without its data loaded.
    public var searchText: String?

    public init(id: String = UUID().uuidString, kind: ClipKind, title: String, files: [String] = [], digest: String, date: Date,
                sourceApp: String? = nil, sourceName: String? = nil, pinned: Bool = false, types: [String], size: Int,
                thumbnail: Data? = nil, searchText: String? = nil) {
        self.id = id
        self.kind = kind
        self.title = title
        self.files = files
        self.digest = digest
        self.date = date
        self.sourceApp = sourceApp
        self.sourceName = sourceName
        self.pinned = pinned
        self.types = types
        self.size = size
        self.thumbnail = thumbnail
        self.searchText = searchText
    }

    /// How much of a copy's text is matched: a copy can be megabytes.
    public static let searchLimit = 2_000

    /// Text as `searchText` keeps it: its start, folded, every run of what is not a letter or a digit one
    /// space — so a query's words are found at the start of its words by a plain scan.
    public static func searchText(from text: String) -> String {
        let folded = Matcher.fold(String(text.prefix(searchLimit)))
        return folded.split(whereSeparator: { !$0.isLetter && !$0.isNumber }).joined(separator: " ")
    }

    /// A title from text: its first line with something in it, trimmed and shortened.
    public static func title(from text: String) -> String {
        let line = text.split(whereSeparator: \.isNewline).first { !$0.trimmingCharacters(in: .whitespaces).isEmpty } ?? ""
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        return trimmed.count > 200 ? String(trimmed.prefix(200)) + "…" : trimmed
    }
}

/// Every copy kept, newest first ([clipboard](product/clipboard.md)).
public struct ClipHistory: Codable, Equatable, Sendable {
    public private(set) var entries: [ClipEntry] = []

    /// 30 days, unless the user says otherwise.
    public static let retention: TimeInterval = 30 * 24 * 3600
    public static let cap = 5_000

    public init(entries: [ClipEntry] = []) {
        self.entries = entries
    }

    /// A new copy at the top; the same thing copied again moves its entry there, dated now. Returns the
    /// entry as kept, and whether it is new — whether its data needs saving.
    @discardableResult
    public mutating func insert(_ entry: ClipEntry) -> (kept: ClipEntry, isNew: Bool) {
        if let index = entries.firstIndex(where: { $0.digest == entry.digest }) {
            var existing = entries.remove(at: index)
            existing.date = entry.date
            existing.sourceApp = entry.sourceApp
            existing.sourceName = entry.sourceName
            entries.insert(existing, at: 0)
            return (existing, false)
        }
        entries.insert(entry, at: 0)
        return (entry, true)
    }

    /// Put back on the clipboard: to the top, dated now.
    public mutating func touch(_ id: String, at date: Date) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        var entry = entries.remove(at: index)
        entry.date = date
        entries.insert(entry, at: 0)
    }

    public mutating func setPinned(_ id: String, _ pinned: Bool) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].pinned = pinned
    }

    @discardableResult
    public mutating func remove(_ id: String) -> ClipEntry? {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return nil }
        return entries.remove(at: index)
    }

    /// A removed entry put back at its place — unless the same thing was copied again since, which brought it
    /// back already. Returns whether it went back.
    @discardableResult
    public mutating func restore(_ entry: ClipEntry, at index: Int) -> Bool {
        guard !entries.contains(where: { $0.id == entry.id || $0.digest == entry.digest }) else { return false }
        entries.insert(entry, at: min(max(index, 0), entries.count))
        return true
    }

    /// Unpinned entries older than `retention`, and past `cap` the oldest unpinned ones: removed and
    /// returned, for their data to go too.
    public mutating func prune(now: Date, retention: TimeInterval = retention, cap: Int = cap) -> [ClipEntry] {
        var removed: [ClipEntry] = []
        entries.removeAll { entry in
            let old = !entry.pinned && now.timeIntervalSince(entry.date) > retention
            if old { removed.append(entry) }
            return old
        }
        var excess = entries.count - cap
        var index = entries.count - 1
        while excess > 0, index >= 0 {
            if !entries[index].pinned {
                removed.append(entries.remove(at: index))
                excess -= 1
            }
            index -= 1
        }
        return removed
    }

    /// Entries whose title, files' names or text match, with how: search's Clipboard section, and the
    /// history's own filter.
    public func matches(_ query: Query) -> [(entry: ClipEntry, match: Match)] {
        let words = query.words.map(ClipEntry.searchText(from:)).filter { !$0.isEmpty }
        return entries.compactMap { entry in
            let names = [entry.title] + entry.files.map { ($0 as NSString).lastPathComponent }
            if let match = names.compactMap({ Matcher.match(query, $0) }).min(by: { $0.kind < $1.kind }) { return (entry, match) }
            // Found in the text past its title: a words match at best, with nothing of the title to bold.
            guard let text = entry.searchText, !words.isEmpty,
                  words.allSatisfy({ text.hasPrefix($0) || text.contains(" " + $0) }) else { return nil }
            return (entry, Match(kind: .words, ranges: []))
        }
    }
}
